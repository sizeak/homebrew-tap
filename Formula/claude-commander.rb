  desc "High-performance terminal UI for managing Claude coding sessions"
  homepage "https://github.com/sizeak/claude-commander"
  url "https://github.com/sizeak/claude-commander/archive/refs/tags/v0.14.1.tar.gz"
  sha256 "c48d36c55e2f12e57e37bdaff6cb3769e472c17b009977eafc23009ed4ad8fc9"
  license "MIT"
  head "https://github.com/sizeak/claude-commander.git", branch: "main"

  depends_on "rust" => :build

